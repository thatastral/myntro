// Builds icons.js (Phosphor Icons, MIT) and art.js (unDraw illustrations) from the npm packs.
// Usage: node tools/build-assets.mjs <dir containing node_modules with @phosphor-icons/core and undraw-svg>
import { readFileSync, writeFileSync } from 'node:fs';
const base = process.argv[2] || '.';
const P = `${base}/node_modules/@phosphor-icons/core/assets`;
const U = `${base}/node_modules/undraw-svg/svgs`;
const inner = s => s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const icons = {};
const want = {
  duotone: ['house', 'note-pencil', 'scales', 'clock', 'person-simple-bike', 'person-simple-run', 'person-simple-walk', 'barbell', 'drop', 'trophy', 'target', 'timer', 'heartbeat', 'cloud-check'],
  fill: ['house', 'note-pencil', 'scales', 'clock', 'flame', 'drop'],
  bold: ['plus', 'x'],
  regular: ['arrow-counter-clockwise', 'check'],
};
for (const [w, names] of Object.entries(want)) for (const n of names) {
  const file = `${P}/${w}/${n}${w === 'regular' ? '' : '-' + w}.svg`;
  icons[`${n}${w === 'regular' ? '' : ':' + w}`] = inner(readFileSync(file, 'utf8'));
}
writeFileSync(new URL('../icons.js', import.meta.url), `// Generated by tools/build-assets.mjs from Phosphor Icons (MIT, https://phosphoricons.com)\nconst IC = ${JSON.stringify(icons)};\nconst ic = (n, c = '') => \`<svg class="ic \${c}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">\${IC[n] || ''}</svg>\`;\n`);

// Recolour unDraw's black figures to the app theme: darks -> theme ink, brand dark -> accent, light greys -> soft fill.
const recolor = svg => svg
  .replace(/<\?xml[^>]*>/, '')
  .replace(/\s(width|height)="[^"]*"/g, (m, k, off, str) => m) // keep root size attrs untouched; CSS sizes it
  .replace(/#090814/gi, 'var(--accent)')
  .replace(/#(2f2e41|2f2e43|3f3d56|3f3d5[0-9a-f])/gi, 'var(--ink)')
  .replace(/#(e6e6e6|d6d6e3|f2f2f2|e5e5e5|cccccc|ccc|e4e4e4|f0f0f0|e6e6e6)/gi, 'var(--bar)');
const art = { workout: 'morning-workout', run: 'running-wild', team: 'athletes-training', stats: 'fitness-stats', nodata: 'no-data', habit: 'healthy-habit' };
const out = {};
for (const [k, f] of Object.entries(art)) out[k] = recolor(readFileSync(`${U}/${f}.svg`, 'utf8')).replace(/<svg /, '<svg class="art-svg" aria-hidden="true" ');
writeFileSync(new URL('../art.js', import.meta.url), `// Generated by tools/build-assets.mjs from unDraw illustrations (https://undraw.co/license), recoloured to the app theme\nconst ART = ${JSON.stringify(out)};\n`);
console.log('icons', Object.keys(icons).length, 'art', Object.keys(out).length);
